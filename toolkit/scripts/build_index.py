#!/usr/bin/env python3
"""build_index.py — regenerate README.md and the home page (index.html) of the
lessons repo from lessons/*/meta.json.

Usage: python3 build_index.py <repo_dir> <owner> <repo>

meta.json fields: title, short, summary, date (YYYY-MM-DD), level, minutes, tags (list)
"""
import html
import json
import sys
from datetime import date
from pathlib import Path

repo_dir, owner, repo = Path(sys.argv[1]), sys.argv[2], sys.argv[3]
base = f"https://{owner.lower()}.github.io/{repo}/"

lessons = []
for meta in sorted((repo_dir / "lessons").glob("*/meta.json")):
    m = json.loads(meta.read_text(encoding="utf-8"))
    m["slug"] = meta.parent.name
    m["url"] = f"{base}lessons/{m['slug']}/"
    lessons.append(m)
lessons.sort(key=lambda m: (m.get("date", ""), m["slug"]), reverse=True)

# ---------------- README ----------------
rows = "\n".join(
    f"| [{m['title']}]({m['url']}) | {m.get('summary','')} | {m.get('level','')} | {m.get('date','')} |"
    for m in lessons
) or "| _No lessons yet_ | | | |"
readme = f"""# STE Study Manuals

Study pages about topics I want to learn, written in **ASD-STE100 Simplified
Technical English**: short sentences, active voice, one instruction in each
step, and one meaning for each word. Each page has drawn diagrams, photos,
charts, interactive models, and a check-in question after each chapter.

**Home page:** {base}

## Lessons

| Page | What it covers | Level | Date |
|---|---|---|---|
{rows}

## How this repo works

- Each lesson is one folder: `lessons/<slug>/index.html` and `lessons/<slug>/meta.json`.
- `assets/manual.css` and `assets/manual.js` give all pages the same design and behavior.
- GitHub Pages serves the `main` branch. This README and `index.html` are generated by
  the `ste-learning` skill (`scripts/build_index.py`) each time a lesson is published.
- Progress (check-ins and checklists) is saved only in your browser.

_Last update: {date.today().isoformat()} · {len(lessons)} lesson{'s' if len(lessons) != 1 else ''}._
"""
(repo_dir / "README.md").write_text(readme, encoding="utf-8")

# ---------------- home page ----------------
def card(m):
    tags = "".join(f'<li class="chip">{html.escape(t)}</li>' for t in m.get("tags", [])[:4])
    return f"""<li><a class="card" href="lessons/{m['slug']}/">
  <span class="label">{html.escape(m.get('date',''))} · {html.escape(str(m.get('level','')))}{(' · ' + str(m['minutes']) + ' min') if m.get('minutes') else ''}</span>
  <h3>{html.escape(m['title'])}</h3>
  <p>{html.escape(m.get('summary',''))}</p>
  <ul class="chips" style="margin:0">{tags}</ul>
</a></li>"""

cards = "\n".join(card(m) for m in lessons) or '<li><div class="card soft"><p>No lessons yet.</p></div></li>'
toc = "\n".join(f'<li><a href="lessons/{m["slug"]}/"><span class="n">{i+1:02d}</span><span>{html.escape(m.get("short") or m["title"])}</span></a></li>' for i, m in enumerate(lessons))
mark = """<svg viewBox="0 0 42 42" aria-hidden="true"><path d="M9 12 L33 8 L36 32 L6 34 Z" fill="var(--accent-soft)" stroke="var(--accent)" stroke-width="2.5" stroke-linejoin="round"/><g fill="var(--bg)" stroke="var(--accent)" stroke-width="2"><circle cx="9" cy="12" r="3"/><circle cx="33" cy="8" r="3"/><circle cx="36" cy="32" r="3"/><circle cx="6" cy="34" r="3"/></g></svg>"""

page = f"""<!doctype html>
<html lang="en"><head>
<meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>STE Study Manuals</title>
<meta name="description" content="Study pages written in ASD-STE100 Simplified Technical English.">
<link rel="icon" href="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 32 32'%3E%3Cpath d='M7 9 L25 6 L27 24 L5 26 Z' fill='%23fbeae3' stroke='%23d97757' stroke-width='2.5' stroke-linejoin='round'/%3E%3C/svg%3E">
<link rel="stylesheet" href="assets/manual.css">
<script src="assets/manual.js" defer></script>
</head><body>
<div class="scrim"></div>
<header class="topbar"><a class="brand" href="./">{mark}<span class="brand-title">Study Manuals</span></a>
<button class="icon-btn" data-action="menu" aria-label="Open contents">Lessons</button></header>
<div class="shell">
<aside class="sidebar">
  <a class="brand" href="./">{mark}<div><div class="brand-title">Study Manuals</div><div class="brand-sub">ASD-STE100 · {len(lessons)} lesson{'s' if len(lessons) != 1 else ''}</div></div></a>
  <nav><ol class="toc">{toc}</ol></nav>
  <div class="side-tools"><button class="icon-btn" data-action="theme" type="button">Theme</button>
  <a class="icon-btn" style="text-decoration:none" href="https://github.com/{owner}/{repo}">GitHub</a></div>
  <p class="side-note">Every page uses ASD-STE100 Simplified Technical English: short sentences, active voice, one meaning for each word.</p>
</aside>
<div class="content"><main>
  <p class="eyebrow">Library · ASD-STE100 style · {date.today().strftime('%d %b %Y').upper()}</p>
  <h1>Study manuals</h1>
  <p class="lede">Each manual explains one topic in Simplified Technical English. Each manual has diagrams, photos, models that you can change, and a check-in question after each chapter.</p>
  <ul class="catalog">
{cards}
  </ul>
  <footer class="page-foot"><span>{len(lessons)} lesson{'s' if len(lessons) != 1 else ''}</span><a href="https://github.com/{owner}/{repo}">Source on GitHub →</a></footer>
</main></div></div>
</body></html>
"""
(repo_dir / "index.html").write_text(page, encoding="utf-8")
print(f"README.md and index.html: {len(lessons)} lessons")
for m in lessons:
    print(" ", m["url"])
